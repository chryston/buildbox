// The Noto Sans assets (#60 §2, #61): the committed metrics table the display list lays text out
// with, the Latin-1 woff2 the canvas draws with, and the Latin-1 TrueType a PDF embeds.
//
//   node scripts/gen-font-assets.mjs
//
// All outputs are committed, so the app never needs `fontkit` or `subset-font` at build or
// run time — they are devDependencies for this file alone. The source `.ttf` stays beside
// them as the provenance of all three, and nothing in `src` imports any of them eagerly
// (#60 criterion 20; the PDF face is loaded by the lazy export chunk only, #61 criterion 15).
//
// The metrics are the advance widths of U+0020–U+007E and U+00A0–U+00FF, the `.notdef` and
// U+FFFD widths, and every non-zero kerning pair inside those two ranges. `drawing/font`
// reads the table; a character outside it is measured as `.notdef` and reported as a missing
// glyph, which is exactly what #19 §4 needs for its notice.
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { openSync } from 'fontkit'
import subsetFont from 'subset-font'

const ROOT = path.resolve(import.meta.dirname, '..')
const SOURCE = path.join(ROOT, 'src/assets/fonts/NotoSans-Regular.ttf')
const METRICS_OUT = path.join(ROOT, 'src/drawing/font/notoSansMetrics.ts')
const WOFF2_OUT = path.join(ROOT, 'src/assets/fonts/NotoSans-Latin1.woff2')
const TTF_OUT = path.join(ROOT, 'src/assets/fonts/NotoSans-Latin1.ttf')

/** The two ranges the table covers: printable ASCII, and Latin-1 from NBSP up. */
const RANGES = [
  { name: 'ascii', from: 0x0020, to: 0x007e },
  { name: 'latin1', from: 0x00a0, to: 0x00ff },
]

const font = openSync(SOURCE)
const unitsPerEm = font.unitsPerEm
const ascender = font.ascent
const descender = font.descent
const notdefWidth = font.getGlyph(0).advanceWidth
const replacementWidth = font.glyphForCodePoint(0xfffd).advanceWidth

/** The advance of one code point, or `null` when the font has no glyph for it. */
const advanceOf = (code) =>
  font.hasGlyphForCodePoint(code) ? font.glyphForCodePoint(code).advanceWidth : null

const codePoints = RANGES.flatMap((range) =>
  Array.from({ length: range.to - range.from + 1 }, (_, i) => range.from + i),
)

const advances = codePoints.map((code) => advanceOf(code) ?? notdefWidth)

// A kern is whatever the layout engine adds to the first glyph's advance when the two sit
// side by side. Noto Sans carries its kerning in GPOS `kern`, so this reads the same value
// the browser will apply — no GPOS parsing, and no pair the font would not actually use.
// Ligatures and contextual substitution are switched off: a pair that substitutes to one
// glyph has no pair value to record, and the table describes advances, not substitutions.
const FEATURES = { kern: true, liga: false, calt: false }
const kerning = []
for (const first of codePoints) {
  const head = String.fromCharCode(first)
  for (const second of codePoints) {
    const layout = font.layout(head + String.fromCharCode(second), FEATURES)
    const delta = layout.positions[0].xAdvance - (advanceOf(first) ?? notdefWidth)
    if (delta !== 0) kerning.push([first, second, delta])
  }
}

const hex = (code) => `0x${code.toString(16).padStart(4, '0')}`
const table = (values) =>
  values
    .map((row, i) => `  ${i % 8 === 0 ? '' : '  '}${row}`)
    .join(',\n')

const body = `// Generated by \`scripts/gen-font-assets.mjs\` from \`src/assets/fonts/NotoSans-Regular.ttf\`
// (SIL Open Font License 1.1, see \`src/assets/fonts/OFL.txt\`). Do not edit by hand.
//
// #60 §2: the whole font table the display list needs to lay text out without a DOM. The
// units are the font's own design units; \`drawing/font/layoutText\` scales them by
// \`sizeMm / unitsPerEm\`. A code point outside \`ADVANCES\` has no glyph here, is measured at
// \`NOTDEF_WIDTH\`, and is reported in \`DisplayList.missingGlyphs\`.

/** Design units per em of Noto Sans Regular. */
export const UNITS_PER_EM = ${unitsPerEm}
/** Typographic ascender above the baseline, in design units. */
export const ASCENDER = ${ascender}
/** Typographic descender below the baseline, in design units (negative). */
export const DESCENDER = ${descender}
/** \`.notdef\`: the box a character with no glyph is measured at. */
export const NOTDEF_WIDTH = ${notdefWidth}
/** U+FFFD REPLACEMENT CHARACTER, for the characters #19 §4 renders as a box. */
export const REPLACEMENT_WIDTH = ${replacementWidth}

/** The code points \`ADVANCES\` covers, in order: ${RANGES.map((r) => `${hex(r.from)}–${hex(r.to)}`).join(', ')}. */
export const CODE_POINT_RANGES: readonly [number, number][] = [
${RANGES.map((r) => `  [${hex(r.from)}, ${hex(r.to)}],`).join('\n')}
]

/** One advance per code point in \`CODE_POINT_RANGES\`, in design units. */
export const ADVANCES: readonly number[] = [
${table(advances)},
]

/** Non-zero kerning pairs inside those ranges: \`[first, second, delta]\`, design units. */
export const KERNING: readonly [number, number, number][] = [
${kerning.length === 0 ? '' : kerning.map(([a, b, d]) => `  [${hex(a)}, ${hex(b)}, ${d}],`).join('\n')}
]
`

writeFileSync(METRICS_OUT, `${body}\n`)

// The screen face: Latin-1 only, which is everything the metrics table claims to measure.
const woff2 = await subsetFont(readFileSync(SOURCE),
  String.fromCharCode(...codePoints),
  { targetFormat: 'woff2' })
writeFileSync(WOFF2_OUT, woff2)

// The paper face (#61): the same coverage as a TrueType collection, because `pdf-lib` embeds a
// subset through fontkit and fontkit subsets a TTF, not a woff2. It is the same 22 kB of glyphs
// rather than the 569 kB source, which is what keeps the lazy export chunk inside its budget.
const ttf = await subsetFont(readFileSync(SOURCE),
  String.fromCharCode(...codePoints),
  { targetFormat: 'truetype' })
writeFileSync(TTF_OUT, ttf)

console.log(`metrics: ${codePoints.length} advances, ${kerning.length} kern pairs -> ${path.relative(ROOT, METRICS_OUT)}`)
console.log(`woff2: ${woff2.byteLength} B -> ${path.relative(ROOT, WOFF2_OUT)}`)
console.log(`ttf: ${ttf.byteLength} B -> ${path.relative(ROOT, TTF_OUT)}`)
